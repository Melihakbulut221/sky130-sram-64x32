"""Short cut of the video (about two minutes).

Reuses the frame builders, figures and layout shots of video/script.py; only the selection of
steps and the narration differ.
"""
import os

from . import figs as FG
from . import shots as SH
from . import style as S
from . import script as L
from .engine import Step

R, T = L.R, L.T
STEPS = []


def add(builder, text):
    STEPS.append((builder, " ".join(text.split())))


sec = "The memory"
add(L.title_slide, """
This is a six transistor SRAM: 64 words of 32 bits, on SkyWater's open source 130 nm process, SKY130.
The cell array is custom layout, generated by Python code, and everything is checked with open tools.
""")

sec = "The cell"
add(L.fig_slide(sec, "Six transistors, one bit", FG.cell_schematic, None), """
Each bit lives in two inverters connected in a loop, and two pass gates connect it to the bit lines.
Sizing the cell is a tug of war. The pull down must beat the pass gate, or a read flips the cell.
And the pass gate must beat the pull up, or a write fails.
""")
add(L.fig_slide(sec, "Butterfly curves: how much noise can the cell take?", FG.butterfly), f"""
I chose the sizes from butterfly curves over all process, voltage and temperature corners.
The worst case read margin is {R['bitcell']['read_worst'] * 1000:.0f} millivolts,
and a thousand Monte Carlo samples per corner show no failures.
""")

sec = "The layout"
add(L.lay_slide(sec, "One cell: 4.85 × 0.91 µm, logic design rules", L.CB, SH.ALL,
                ann=[(L.CELL[0], L.CELL[1], L.CELL[2], L.CELL[3], "one cell", S.YELLOW)]), """
The cell is drawn with the ordinary logic design rules, so the standard rule decks apply without any waivers.
That costs area: it is about twice the size of the foundry's own cell.
""")
add(L.lay_anim(sec, "From one cell to the array", L.CB, L.MACRO, dur=5.0), f"""
Mirrored neighbours share their contacts. Sixty four rows of thirty two cells make the array: {R['array_mosfets']:,} transistors.
""")

sec = "The periphery"
add(L.fig_slide(sec, "One clock, two phases", FG.timing_diagram), """
Around the array there is no sense amplifier, and no self timed pulse. The bit lines swing from rail to rail, and a plain inverter senses them.
The bit lines precharge while the clock is high, and the access happens while it is low. If a phase is too short, you slow the clock down.
""")
add(L.lay_slide(sec, f"The complete memory: {R['die_w']:g} × {R['die_h']:g} µm", L.FULL, SH.ALL,
                ann=[(L.MACRO[0], L.MACRO[1], L.MACRO[2], L.MACRO[3], "6T array (custom)", S.YELLOW, "in"),
                     (6, L.MY, L.MX - 1, L.MY + R["macro_h"], "row decoder", S.CYAN, "in"),
                     (6, 11, L.FULL[2] - 6, L.MY - 1, "column circuits, input registers, clocking (standard cells)", S.PURPLE, "in")]), f"""
That periphery is ordinary Verilog, placed and routed as standard cells next to the array. The complete memory measures {R['die_w']:g} by {R['die_h']:g} µm.
""")

sec = "Does it work?"
add(L.term_slide(sec, "Sign-off of the complete memory", L.read("out/signoff_chip_summary.txt"),
                 notes=[("h", "Final layout"), "Design rules: Magic and KLayout", "Antenna, power grid and timing checks",
                        ("LVS flat, down to every transistor", S.GREEN)]), """
The final layout has zero design rule violations in two independent checkers, and it matches its netlist transistor by transistor.
""")
add(L.fig_slide(sec, "Post-layout SPICE: write, then read", FG.waves, os.path.join(L.OUT, "chipc_tt.npz"), R["wave_t0"], R["wave_t1"],
                "", R["wave_rows"], 20e-9, R["wave_marks"]), f"""
In SPICE on the extracted layout, a word is written and read back. The data is out {T['tt']['t_cq_max']:.1f} nanoseconds after the clock edge,
and {T['ss']['t_cq_max']:.1f} nanoseconds at the slow corner.
""")
add(L.bullet_slide(sec, "What you get, and what is still missing", [
    ("h", "In the repository"),
    "GDS, LEF, Liberty for three corners, Verilog model, SPICE netlists",
    "A March C- self-test, placed and routed together with the macro",
    "Every step reproducible from code",
    ("h", "Not done"),
    ("No silicon. Nothing here has been fabricated or measured.", S.ORANGE),
], size=36), """
It comes with timing libraries, a simulation model and a self test. What it does not have yet is silicon: nothing here has been fabricated.
The full video, and all of the code, are on GitHub.
""")


def build_steps():
    n = len(STEPS)
    return [Step(builder(i / max(1, n - 1)), text) for i, (builder, text) in enumerate(STEPS)]
